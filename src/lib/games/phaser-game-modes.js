export function getPhaserGameMode(mode = 'catch-falling') {
  return PHASER_GAME_MODES[mode] || PHASER_GAME_MODES['catch-falling']
}

export function getPhaserModesForGrade(gradeSlug = 'lop-1') {
  return Object.entries(PHASER_GAME_MODES)
    .filter(([, mode]) => mode.grades.includes(gradeSlug))
    .map(([id, mode]) => ({ id, ...mode }))
}
